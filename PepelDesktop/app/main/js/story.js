// ---------- Сборка диалога с NPC ----------
function buildTalk(npcId) {
  const nd = NPCS[npcId] || { n: npcId };
  const sc = [];
  const sp = SPECIAL[npcId] && SPECIAL[npcId]();
  if (sp) sc.push(...sp);
  for (const qid in QUESTS) {
    const q = QUESTS[qid], st = S.quests[qid];
    if (!st || st.st !== 'active') continue;
    const step = q.steps[st.step];
    if (step && step.k === 'talk' && step.npc === npcId && step.lines && step.lines.length) {
      sc.push(...step.lines); sc.push({ fn: () => QP('talk', npcId, 1, qid) });
    } else if (step && step.k === 'talk' && step.npc === npcId) sc.push({ fn: () => QP('talk', npcId, 1, qid) });
  }
  for (const qid in QUESTS) {
    const q = QUESTS[qid];
    if (q.giver !== npcId || S.quests[qid] || q.auto || !q.offer) continue;
    if (q.req && !q.req()) continue;
    sc.push(...q.offer);
    sc.push({ choices: [['Принять задание', () => { startQuest(qid); return q.accept || []; }], ['Не сейчас', () => [[nd.n, 'Хорошо. Возвращайся, когда будешь готов.']]]] });
  }
  if (!sc.length) sc.push(...(IDLE[npcId] ? IDLE[npcId]() : [[nd.n, '...']]));
  const menu = [];
  if (nd.shop) menu.push(['Торговать', () => { UI.openShop(npcId); }]);
  if (nd.forge) menu.push(['Улучшить снаряжение', () => { UI.openForge(); }]);
  if (nd.heal) menu.push(['Исцелиться (15 зол.)', () => { G.healService(); }]);
  if (nd.craft) menu.push(['Создать предмет (' + STATION_N[nd.craft] + ')', () => { UI.openCraft(nd.craft); }]);
  if (nd.ench) menu.push(['Зачаровать снаряжение', () => { UI.openEnchant(); }]);
  (nd.acts || []).forEach(a => { if (ACTS[a]) menu.push([ACTS[a].label, () => ACTS[a].run(npcId)]); });
  if (npcId === 'brogar' || npcId === 'liara') { /* только торговля */ }
  if (menu.length) { menu.push(['Уйти', () => { }]); sc.push({ choices: menu }); }
  return sc;
}
